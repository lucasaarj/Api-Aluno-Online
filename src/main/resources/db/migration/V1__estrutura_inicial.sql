-- Esquema inicial da API Aluno Online.
-- Em bancos já existentes, o Flyway registra esta versão por baseline
-- e executa somente as migrations posteriores.

CREATE TABLE aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    cpf VARCHAR(255),
    email VARCHAR(255)
);

CREATE TABLE professor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    cpf VARCHAR(255),
    email VARCHAR(255)
);

CREATE TABLE disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    carga_horaria INTEGER,
    professor_id BIGINT,
    CONSTRAINT fk_disciplina_professor
        FOREIGN KEY (professor_id) REFERENCES professor (id)
);

CREATE TABLE matricula_aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT,
    disciplina_id BIGINT,
    nota1 DOUBLE PRECISION,
    nota2 DOUBLE PRECISION,
    status VARCHAR(255),
    CONSTRAINT fk_matricula_aluno_aluno
        FOREIGN KEY (aluno_id) REFERENCES aluno (id),
    CONSTRAINT fk_matricula_aluno_disciplina
        FOREIGN KEY (disciplina_id) REFERENCES disciplina (id)
);
