CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(254) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    aluno_id BIGINT,
    professor_id BIGINT,
    CONSTRAINT uk_usuarios_login UNIQUE (login),
    CONSTRAINT uk_usuarios_aluno UNIQUE (aluno_id),
    CONSTRAINT uk_usuarios_professor UNIQUE (professor_id),
    CONSTRAINT fk_usuarios_aluno
        FOREIGN KEY (aluno_id) REFERENCES aluno (id),
    CONSTRAINT fk_usuarios_professor
        FOREIGN KEY (professor_id) REFERENCES professor (id),
    CONSTRAINT ck_usuarios_vinculo_exclusivo CHECK (
        (aluno_id IS NOT NULL AND professor_id IS NULL)
        OR
        (aluno_id IS NULL AND professor_id IS NOT NULL)
    )
);
